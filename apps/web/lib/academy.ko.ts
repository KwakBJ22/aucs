export function findLesson(key: string) {
  for (const s of STAGES) {
    const i = s.lessons.findIndex((l) => l.key === key);
    if (i >= 0) return { stage: s, lesson: s.lessons[i]!, next: s.lessons[i + 1] ?? null };
  }
  return null;
}
